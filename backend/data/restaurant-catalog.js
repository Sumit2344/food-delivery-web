function createMenu(prefix, rows) {
  return rows.map(([name, category, price, type, description], index) => {
    const rating = Number((4 + ((index * 3 + prefix.length) % 10) / 10).toFixed(1))
    return {
      id: `${prefix}-${name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
      name,
      category,
      price,
      type,
      description,
      popular: index < 3,
      votes: 8 + ((index * 17 + name.length) % 70),
      rating,
      reviewCount: 1,
      reviews: [{
        author: 'Sample diner',
        rating,
        text: `${reviewNotes[(index + prefix.length) % reviewNotes.length]} ${name} was a good pick.`,
      }],
    }
  })
}

